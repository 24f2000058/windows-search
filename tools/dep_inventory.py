#!/usr/bin/env python3
"""Writes docs/dependencies.md from `cargo metadata` (all targets, incl. Windows).

Usage: python3 tools/dep_inventory.py > docs/dependencies.md
"""
import json, subprocess, sys

def meta(target=None):
    cmd = ["cargo", "metadata", "--format-version", "1", "--locked"]
    if target:
        cmd += ["--filter-platform", target]
    return json.loads(subprocess.check_output(cmd))

seen = {}
for target in ["x86_64-pc-windows-msvc", "x86_64-unknown-linux-gnu"]:
    m = meta(target)
    resolved = {n["id"] for n in m["resolve"]["nodes"]}
    for p in m["packages"]:
        if p["id"] in resolved and p["source"]:
            seen[(p["name"], p["version"])] = p.get("license") or "UNKNOWN"
print("# Third-party dependency inventory\n")
print("Generated by `tools/dep_inventory.py` from `Cargo.lock` (Windows MSVC and Linux targets).")
print("Regenerate on every dependency change; CI should fail on UNKNOWN or copyleft licenses")
print("that are not explicitly approved. Bundled native code: SQLite (public domain) via")
print("`libsqlite3-sys` with the `bundled` feature.\n")
print("| Crate | Version | License |\n|---|---|---|")
for (n, v), lic in sorted(seen.items()):
    print(f"| {n} | {v} | {lic} |")
lics = sorted(set(seen.values()))
print(f"\n{len(seen)} crates. Distinct license expressions: " + "; ".join(f"`{l}`" for l in lics))
